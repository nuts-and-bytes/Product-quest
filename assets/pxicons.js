/* 生成SVG字符串（逐行合并连续像素为rect，体积小） */
PQ.pxi = function(name, size, color){
  const map = PQ.pxiMaps[name] || PQ.pxiMaps.spark;
  size = size || 16; color = color || 'currentColor';
  let rects = '';
  map.forEach((row, y) => {
    let x = 0;
    while (x < 10) {
      if (row[x] === '#') {
        let w = 1;
        while (x + w < 10 && row[x + w] === '#') w++;
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1"/>`;
        x += w;
      } else x++;
    }
  });
  return `<svg class="pxis" width="${size}" height="${size}" viewBox="0 0 10 10" fill="${color}" shape-rendering="crispEdges" xmlns="http://www.w3.org/2000/svg" style="vertical-align:-2px">${rects}</svg>`;
};

/* 把 <i data-pxi="name" data-size data-color> 占位符替换为SVG */
PQ.hydratePxi = function(root){
  (root || document).querySelectorAll('i[data-pxi]').forEach(el => {
    el.innerHTML = PQ.pxi(el.dataset.pxi, parseInt(el.dataset.size || '16', 10), el.dataset.color || 'currentColor');
  });
};

